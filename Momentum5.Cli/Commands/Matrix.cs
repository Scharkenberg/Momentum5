using System.CommandLine;
using System.Globalization;
using System.Text;
using Momentum5.Core.Settings;
using Momentum5.Protocol;
using Momentum5.Protocol.Bindings;

namespace Momentum5.Cli;

/// <summary>Verification matrix: one markdown row per binding; the user fills result/date/firmware during hardware runs.</summary>
internal static class Matrix
{
	// GET words seen byte-for-byte in the Aria M5 fixtures or the R-04 captures.
	private static readonly HashSet<ushort> CapturedGets =
	[
		0x1206, 0x1201, 0x1A01, 0x1A03, 0x1A05, 0x1801, 0x1805, 0x1000, 0x1009, 0x1607, 0x0401,
		0x080B, 0x080D, 0x0815, 0x0802, 0x0804, 0x1003, 0x0603,
	];

	private static readonly (string Topic, string Note)[] OpenSemantics =
	[
		("Touch-lock polarity (1606/1607)", "[CAP2] 1 = locked; confirm TouchControlsEnabled inversion by toggling on the headset and reading back."),
		("Sidetone / Comfort Calls (0814/0815)", "[CAP2] boolean, no range; confirm there is no separate sidetone level."),
		("Low-latency SET (0817/0818)", "Unverified, Gated: verify write + read-back on 6.21.5 before enabling in the UI."),
	];

	public static Command Build(GlobalOptions g)
	{
		var output = new Option<string?>("--out") { Description = "Write the table to this file instead of stdout." };
		var command = new Command("matrix", "Emit the verification matrix as markdown.") { output };
		command.SetAction(result =>
		{
			var text = Render();
			if (result.GetValue(output) is { } path)
			{
				File.WriteAllText(path, text, new UTF8Encoding(false));
				Console.Error.WriteLine($"Wrote {path}");
			}
			else
			{
				Console.Write(text);
			}
		});
		return command;
	}

	public static string Render()
	{
		var sb = new StringBuilder();
		sb.Append("# Verification matrix\n\n");
		sb.Append("Generated by `m5ctl matrix`. Fill Result / Date / Firmware during hardware runs (G2 `m5ctl selftest`); any FAIL becomes an ERRATA entry.\n\n");
		sb.Append("| Key | Vendor | GET | SET | Push | Safety | Status | Expected frames | Result | Date | Firmware |\n");
		sb.Append("|---|---|---|---|---|---|---|---|---|---|---|\n");
		foreach (var b in GaiaCatalog.Bindings)
		{
			var status = b.GetCmd is { } g && CapturedGets.Contains(GaiaWord.AsCommand(g)) ? "GET captured" : "unverified";
			sb.Append(CultureInfo.InvariantCulture, $"| {b.Name}{(b.Indexed ? "[i]" : string.Empty)} | {(b.Vendor == GaiaVendor.Sennheiser ? "S" : "Q")} | {Word(b.GetCmd)} | {Word(b.SetCmd)} | {Word(b.PushCmd)} | {b.Safety} | {status} | {Expected(b)} |  |  |  |\n");
		}

		sb.Append("\n## Open semantics\n\n| Topic | Note | Result |\n|---|---|---|\n");
		foreach (var (topic, note) in OpenSemantics)
		{
			sb.Append(CultureInfo.InvariantCulture, $"| {topic} | {note} |  |\n");
		}

		return sb.ToString();
	}

	private static string Word(ushort? word) => word is { } w ? w.ToString("X4", CultureInfo.InvariantCulture) : "-";

	private static string Expected(ISettingBinding b)
	{
		var parts = new List<string>();
		if (b.GetCmd is { } get)
		{
			parts.Add("GET `" + GaiaFormatter.Hex(new GaiaFrame(b.Vendor, get, b.BuildGetPayload(b.Indexed ? 0 : -1)).Encode()) + "`");
		}

		if (b.SetCmd is { } set && b.SampleValues.Count > 0
			&& b.TryEncodeSet(b.SampleValues[0], b.Indexed ? 0 : -1, out var payload, out _))
		{
			parts.Add("SET(sample) `" + GaiaFormatter.Hex(new GaiaFrame(b.Vendor, set, payload).Encode()) + "`");
		}

		return parts.Count > 0 ? string.Join("<br>", parts) : "-";
	}
}
